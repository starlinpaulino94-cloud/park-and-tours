export function Icon({ name, ...props }: { name: string } & LucideProps) {
  const Cmp = REGISTRY[name];
  if (!Cmp) {
    console.warn(`[icon] icono no registrado: "${name}" — añádelo en src/components/tf/icon.tsx`);
    return <Circle {...props} />;
  }
  return <Cmp {...props} />;
}

